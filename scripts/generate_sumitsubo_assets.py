#!/usr/bin/env python3
"""Generate Sumitsubo Reader's logo bitmaps from the drawing in assets/images/sumitsubo.png.

They take the place of Matcha Reader's cat, which is not MIT and may not be used by a fork under
another name (see assets/images/LICENSE). The files and the names inside them are kept, so the
code that draws them is unchanged:

  src/images/CatLogo.h                      boot/sleep logo and a smaller copy
  src/components/icons/endOfBookCat.h       end-of-book graphic
  src/network/html/assets/matcha-icon.svg   web header and favicon

    python3 scripts/generate_sumitsubo_assets.py

The drawing has grey shading. A 1-bit screen has none, so the outlines and the ink are kept as
black, the wood becomes white, and the darker greys become diagonal hatching, cut at each output
size so that its lines are whole pixels.
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageFilter

from generate_mascot_assets import _fill_holes, c_array, deflate

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "images" / "sumitsubo.png"
LOGO_WIDTH, SMALL_LOGO_WIDTH, EOB_SIZE, WEB_SIZE = 440, 200, 152, 128
INK, SHADE = 110, 190          # below INK: outline or ink. Between the two: the drawing's shadows.


def art():
    src = Image.open(SOURCE).convert("L")
    box = src.point(lambda v: 255 if v < 235 else 0).getbbox()
    return src.crop((box[0] - 12, box[1] - 12, box[2] + 12, box[3] + 12))


def one_bit(src, width, hatch=5):
    """(ink, footprint) at this width, as lists of booleans, row-major; and the height."""
    height = round(src.size[1] * width / src.size[0])
    g = src.resize((width, height), Image.LANCZOS)
    px = g.tobytes()
    ink = [v < INK or (hatch and v < SHADE and (i % width + i // width) % hatch < 2) for i, v in enumerate(px)]
    solid = _fill_holes(g.point(lambda v: 255 if v < 240 else 0)).filter(ImageFilter.MaxFilter(7))   # a white edge round it on the dark sleep screen
    return ink, [v >= 128 for v in solid.tobytes()], height


def build_logo(src, width):
    ink, inside, height = one_bit(src, width)
    symbols = [(0 if k else 3) | (int(f) << 2) for k, f in zip(ink, inside)]
    rle = bytearray()
    i = 0
    while i < len(symbols):
        run = 1
        while i + run < len(symbols) and symbols[i + run] == symbols[i] and run < 32:
            run += 1
        rle.append(symbols[i] << 5 | (run - 1))
        i += run
    return width, height, rle


def build_end_of_book(src):
    ink, _, height = one_bit(src, EOB_SIZE, hatch=4)
    top = (EOB_SIZE - height) // 2
    black = lambda x, y: top <= y < top + height and ink[(y - top) * EOB_SIZE + x]
    # drawIcon plots stored (row, col) at screen (size - 1 - row, col): rows run right to left.
    row_bytes = (EOB_SIZE + 7) // 8
    packed = bytearray([0xFF] * (row_bytes * EOB_SIZE))
    for row in range(EOB_SIZE):
        for col in range(EOB_SIZE):
            if black(EOB_SIZE - 1 - row, col):
                packed[row * row_bytes + (col >> 3)] &= ~(0x80 >> (col & 7)) & 0xFF
    return packed


def build_web_icon(src):
    w = WEB_SIZE
    h = round(src.size[1] * w / src.size[0])
    g = src.resize((w, h), Image.LANCZOS).point(lambda v: 255 if v > SHADE else v)       # smooth lines, no shading
    alpha = _fill_holes(g.point(lambda v: 255 if v < 240 else 0))
    rgba = Image.merge("RGBA", (g, g, g, alpha))
    icon = Image.new("RGBA", (w, w), (0, 0, 0, 0))
    icon.paste(rgba, (0, (w - h) // 2))
    buf = io.BytesIO()
    icon.save(buf, "PNG", optimize=True)
    data = base64.b64encode(buf.getvalue()).decode()
    return ("<!-- The Sumitsubo ink pot. See assets/images/LICENSE. -->\n"
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{w}" viewBox="0 0 {w} {w}">'
            f'<image width="{w}" height="{w}" href="data:image/png;base64,{data}"/></svg>\n')


def main():
    src = art()
    width, height, logo = build_logo(src, LOGO_WIDTH)
    sw, sh, small = build_logo(src, SMALL_LOGO_WIDTH)
    note = ("// The Sumitsubo ink pot, in place of Matcha Reader's cat (the names are kept so the code that draws it\n"
            "// is unchanged). Generated by scripts/generate_sumitsubo_assets.py from assets/images/sumitsubo.png.\n")
    (ROOT / "src" / "images" / "CatLogo.h").write_text(
        "#pragma once\n#include <cstdint>\n\n"
        f"// {width}x{height} logo, run-length coded: each byte is (symbol << 5) | (run - 1), runs of 1-32\n"
        "// pixels in row-major order, continuing across rows. symbol = footprint << 2 | level, where\n"
        "// level 0 = black, 1 = dark gray, 2 = light gray, 3 = white, and footprint marks the drawing and a\n"
        "// white edge around it, which the dark sleep screen keeps lit.\n" + note +
        f"static constexpr int CAT_LOGO_WIDTH = {width};\nstatic constexpr int CAT_LOGO_HEIGHT = {height};\n"
        f"static const uint8_t CatLogoRle[] = {{\n{c_array(logo)}\n}};\n\n"
        "// The same at a smaller size, coded the same way and then raw-deflated: it is drawn only by\n"
        "// the Departures sleep screen, which inflates it into a CAT_LOGO_SMALL_RLE_SIZE buffer.\n"
        f"static constexpr int CAT_LOGO_SMALL_WIDTH = {sw};\nstatic constexpr int CAT_LOGO_SMALL_HEIGHT = {sh};\n"
        f"static constexpr int CAT_LOGO_SMALL_RLE_SIZE = {len(small)};\n"
        f"static const uint8_t CatLogoSmallDeflated[] = {{\n{c_array(deflate(small))}\n}};\n")
    (ROOT / "src" / "components" / "icons" / "endOfBookCat.h").write_text(
        "#pragma once\n#include <cstdint>\n\n// End-of-book graphic, 1 bpp, drawn with GfxRenderer::drawIcon.\n" + note +
        f"static constexpr int END_OF_BOOK_CAT_SIZE = {EOB_SIZE};\n"
        f"static const uint8_t EndOfBookCat[] = {{\n{c_array(build_end_of_book(src))}\n}};\n")
    (ROOT / "src" / "network" / "html" / "assets" / "matcha-icon.svg").write_text(build_web_icon(src))
    print(f"logo {width}x{height} ({len(logo)} bytes), small {sw}x{sh}, end of book {EOB_SIZE}, web {WEB_SIZE}")


if __name__ == "__main__":
    main()
